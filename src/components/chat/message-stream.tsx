'use client';

import React, { useState } from 'react';
import { Sparkles, Copy, Check } from 'lucide-react';
import { MarkdownMathRenderer } from '../math/markdown-math-renderer';
import type { AnswerStatus } from '../../types/question';
import type { ChatSuggestion } from '../../types/chat';
import { SourceArtifact, type ArtifactSource } from './source-artifact';

interface MessageStreamProps {
  content: string;
  isStreaming?: boolean;
  status?: AnswerStatus;
  sources?: ArtifactSource[];
  suggestions?: ChatSuggestion[];
  onSuggestionClick?: (prompt: string) => void;
}

const STATUS_LABEL: Record<AnswerStatus, string | null> = {
  answered: 'Answer from the papers',
  insufficient: 'Explanation generated by AI; related questions from papers',
  out_of_scope: null, // body already says not-in-papers + optional AI note
  guidance: null, // friendly coach reply — no scary banner
};

export const MessageStream: React.FC<MessageStreamProps> = ({
  content,
  isStreaming = false,
  status,
  sources = [],
  suggestions = [],
  onSuggestionClick,
}) => {
  const [copied, setCopied] = useState(false);

  const handleCopy = async () => {
    if (!content) return;
    try {
      await navigator.clipboard.writeText(content);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (err) {
      console.error('Failed to copy response:', err);
    }
  };

  if (!content) {
    return (
      <div
        className="w-full max-w-2xl mr-auto flex items-center gap-2.5 text-xs sm:text-sm text-slate-700 py-4 px-5 rounded-2xl shadow-sm animate-pulse bg-[#F5F5F5] border border-[#E6E6E6]"
        style={{
          backgroundColor: '#F5F5F5',
          border: '1px solid #E6E6E6',
        }}
      >
        <span className="w-2 h-2 rounded-full bg-[#2665D9] animate-ping" />
        Searching curated question archive and analyzing difficulty...
      </div>
    );
  }

  const label = status ? STATUS_LABEL[status] : null;

  return (
    <div className="w-full max-w-2xl mr-auto space-y-2">
      <div
        className="relative group space-y-4 text-left font-sans p-6 sm:p-8 rounded-2xl shadow-sm bg-[#F5F5F5] border border-[#E6E6E6] overflow-hidden min-w-0 max-w-full"
        style={{
          backgroundColor: '#F5F5F5',
          border: '1px solid #E6E6E6',
        }}
      >
        {!isStreaming && (
          <button
            type="button"
            onClick={handleCopy}
            aria-label={copied ? 'Copied response' : 'Copy response'}
            title={copied ? 'Copied!' : 'Copy response'}
            className="absolute top-3 right-3 sm:top-4 sm:right-4 opacity-0 group-hover:opacity-100 focus:opacity-100 transition-opacity p-1.5 sm:p-2 rounded-xl text-slate-500 hover:text-slate-800 hover:bg-slate-200/80 bg-[#F5F5F5]/90 backdrop-blur-xs border border-slate-200/60 shadow-xs cursor-pointer z-10 flex items-center gap-1.5 text-xs font-medium"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-600" />
                <span className="text-emerald-700 text-[11px] font-medium">Copied</span>
              </>
            ) : (
              <Copy className="w-3.5 h-3.5" />
            )}
          </button>
        )}

        {label && (
          <p className="text-xs font-semibold uppercase tracking-wide text-slate-500 pr-12">
            {label}
          </p>
        )}
        <MarkdownMathRenderer content={content} />
        {isStreaming && (
          <span className="inline-block w-2 h-4 ml-1 bg-[#2665D9] animate-pulse align-middle" />
        )}
      </div>

      {!isStreaming && <SourceArtifact sources={sources} />}

      {!isStreaming && suggestions && suggestions.length > 0 && (
        <div className="pt-1.5 flex flex-wrap items-center gap-2 animate-in fade-in duration-200">
          <span className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider w-full select-none">
            Suggested follow-ups
          </span>
          {suggestions.map((s, idx) => (
            <button
              key={`${s.label}-${idx}`}
              type="button"
              onClick={() => onSuggestionClick?.(s.prompt)}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-full text-xs font-medium bg-white text-slate-700 border border-slate-200 shadow-sm hover:border-blue-300 hover:bg-blue-50/70 hover:text-blue-700 transition-all cursor-pointer active:scale-95 group"
            >
              <Sparkles className="w-3 h-3 text-blue-500 group-hover:scale-110 transition-transform shrink-0" />
              <span>{s.label}</span>
            </button>
          ))}
        </div>
      )}
    </div>
  );
};
